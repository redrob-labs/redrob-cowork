/**
 * The "logical" key for a translation entry: the bare key for non-plural
 * entries, or the shared base for a `_zero` / `_one` / `_two` / `_few` /
 * `_many` / `_other` plural family. Korean has no grammatical plural, so a
 * translated bundle only ever needs the base form.
 *
 * Used by `ko.ts` (via `satisfies Record<EnglishLogicalKey, string>`) to make
 * a missing or misspelled Korean key a `tsc` error instead of a silent
 * runtime fallback to English.
 */
export type EnglishLogicalKey = {
  [K in keyof typeof en]: K extends `${infer Base}_${"zero" | "one" | "two" | "few" | "many" | "other"}`
    ? Base
    : K;
}[keyof typeof en];

export default en;
