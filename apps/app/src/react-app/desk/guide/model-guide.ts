/** The harness id of a pick that runs here, in Redrob Cowork. */
const REDROB_HARNESS = "redrob-desk";

/**
 * The research behind "By profession": each profession's top five tasks, and the five best models (or model
 * chains) for each task in English, Korean and Hindi, each with a monthly API cost, ranked again for each
 * deliverable the task makes. Generated by `scripts/model-guide/build.mjs` from a dated leaderboard snapshot;
 * every figure carries where it came from.
 */
const Kind = z.enum(["measured", "published", "derived", "estimate"]);
const Label = z.object({ en: z.string(), ko: z.string() });

const Source = z.object({
  label: z.string(),
  value: z.string(),
  kind: Kind,
  url: z.string().optional(),
  date: z.string(),
  /** On a price row: whose price. */
  model: z.string().optional(),
});

const Pick = z.object({
  id: z.string(),
  steps: z.array(z.object({ model: z.string(), effort: z.string().optional(), role: z.literal("image").optional() })),
  harness: z.string(),
  kind: Kind,
  score: z.object({ quality: z.number(), reliability: z.number(), speed: z.number(), cost: z.number(), ci: z.number() }),
  monthly: z.number(),
  monthlyKind: Kind,
  monthlyRange: z.tuple([z.number(), z.number()]),
  /** Every effort the first model runs at, cheapest first, with a month of the task at it. */
  efforts: z.array(z.tuple([z.string(), z.number()])),
  missing: z.array(z.string()),
  flags: z.array(z.string()),
  sources: z.array(Source),
  /** The same ranking on another product, shown greyed for comparison. */
  benchmark: z.boolean().optional(),
});

export const GuideResearch = z.object({
  asOf: z.string(),
  weights: z.object({ quality: z.number(), reliability: z.number(), speed: z.number(), cost: z.number() }),
  models: z.record(z.string(), z.string()),
  /**
   * Each ranked model's id in the Redrob catalogue, null where Redrob does not serve it. Optional: an edition
   * Console published before the catalogue was added has none.
   */
  catalogue: z.record(z.string(), z.string().nullable()).optional(),
  professions: z.array(
    z.object({
      id: z.string(),
      label: Label,
      tasks: z.array(
        z.object({
          id: z.string(),
          label: Label,
          runs: z.number(),
          tools: z.array(z.string()),
          /** The deliverables the task is ranked for, a subset of GUIDE_OUTPUTS. */
          outputs: z.array(z.string()),
          picks: z.record(z.string(), z.array(Pick)),
          /** By output, then by working language. */
          picksByOutput: z.record(z.string(), z.record(z.string(), z.array(Pick))),
        }),
      ),
    }),
  ),
});
export type GuideResearch = z.infer<typeof GuideResearch>;
type ResearchPick = z.infer<typeof Pick>;

