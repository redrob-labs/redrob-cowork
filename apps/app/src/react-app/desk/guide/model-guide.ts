/** An id the app has no name for shows as itself rather than as a missing-key path. */
function named(names: Record<string, () => string>, id: string): string {
  return names[id]?.() ?? id;
}

function effortName(effort: string): string {
  return named(EFFORTS, effort);
}

/** The ranked effort on the first model's own scale, and every level a reader can try. */
function efforts(pick: ResearchPick): { effort?: Effort; efforts: EffortLevel[] } {
  const ranked = pick.steps[0]?.effort;
  const of = pick.efforts.length;
  const levels = pick.efforts.map(([label, monthly], i) => ({ label: effortName(label), level: i + 1, of, monthly }));
  const at = pick.efforts.findIndex(([label]) => label === ranked);
  if (!ranked) return { efforts: levels };
  return { effort: at < 0 ? { label: effortName(ranked) } : { label: effortName(ranked), level: at + 1, of }, efforts: levels };
}

function sourceLabel(source: z.infer<typeof Source>, models: Record<string, string>): string {
  switch (source.label) {
    case "price":
      return t("desk.guide_source_price", { model: models[source.model ?? ""] ?? source.model ?? "" });
    case "monthly":
      return t("desk.guide_source_monthly");
    case "image":
      return t("desk.guide_source_image");
    default:
      return source.label;
  }
}

/** The research pick each shown pick came from, so "Use this" reads ids rather than display names. */
const SOURCE = new WeakMap<GuidePick, ResearchPick>();

/** What "Use this" does with a pick: the Redrob model and level new chats start on, or why it cannot. */
export type GuideUse =
  | { ok: true; model: ModelRef; variant: string | null; name: string; effort: string | null }
  | { ok: false; reason: "elsewhere"; name: string; harness: string }
  | { ok: false; reason: "not-on-redrob"; name: string };

/**
 * The model a pick runs, as the chat's model menu names it: provider `redrob` and the model's catalogue id, at
 * the level the reader tried or else the ranked one. A pick that runs on another product, or a model Redrob
 * does not serve, cannot be used. A pick that runs a text model then an image model starts the chat on the
 * text model: the chat has one model, and the levels belong to it.
 */
export function guideUse(research: GuideResearch, pick: GuidePick, tried: EffortLevel | null): GuideUse | null {
  const source = SOURCE.get(pick);
  const first = source?.steps[0];
  if (!source || !first) return null;
  const name = research.models[first.model] ?? first.model;
  if (source.harness !== REDROB_HARNESS) return { ok: false, reason: "elsewhere", name, harness: named(HARNESSES, source.harness) };
  const id = research.catalogue?.[first.model];
  if (!id) return { ok: false, reason: "not-on-redrob", name };
  const level = tried?.level ? source.efforts[tried.level - 1]?.[0] : undefined;
  const effort = level ?? first.effort ?? null;
  // "default" sends no level: the provider's own default, which is what an empty variant means.
  const variant = effort && effort !== "default" ? effort : null;
  return { ok: true, model: { providerID: REDROB_PROVIDER_ID, modelID: id }, variant, name, effort: variant ? effortName(variant) : null };
}

function toPick(pick: ResearchPick, tools: string[], research: GuideResearch): GuidePick {
  const name = (model: string) => research.models[model] ?? model;
  const sources: GuideSource[] = pick.sources.map((source) => ({
    label: sourceLabel(source, research.models),
    value: source.value,
    kind: source.kind,
    url: source.url,
    date: source.date,
  }));
  const evidence = pick.sources.filter((source) => !["price", "monthly", "image"].includes(source.label));
  const chain = pick.steps.length > 1;
  const ranked = efforts(pick);
  const shown: GuidePick = {
    id: pick.id,
    ...(chain
      ? {
          steps: pick.steps.map((step, i) => ({
            model: name(step.model),
            // The first step is the model the efforts belong to, so it carries the same meter.
            effort: i === 0 ? ranked.effort : step.effort ? { label: effortName(step.effort) } : undefined,
            role: t(step.role === "image" ? "desk.guide_role_image" : "desk.guide_role_text"),
          })),
        }
      : { model: name(pick.steps[0]?.model ?? "") }),
    harness: named(HARNESSES, pick.harness),
    kind: pick.kind,
    score: pick.score,
    monthly: pick.monthly,
    monthlyKind: pick.monthlyKind,
    monthlyRange: pick.monthlyRange,
    tools: tools.map(
      (tool): GuideTool => ({
        label: named(TOOLS, tool),
        missing: pick.missing.includes(tool),
      }),
    ),
    flags: pick.flags.map((flag) => named(FLAGS, flag)),
    why: evidence
      .slice(0, 2)
      .map((source) => `${source.label}: ${source.value}`)
      .join("; "),
    sources,
    ...(pick.benchmark ? { benchmark: true } : {}),
    ...ranked,
  };
  SOURCE.set(shown, pick);
  return shown;
}

/** The research as ModelGuide professions, labelled in the app's language. */
export function guideProfessions(research: GuideResearch, locale: Language): GuideProfession[] {
  return research.professions.map((profession) => ({
    id: profession.id,
    label: profession.label[locale],
    tasks: profession.tasks.map((task) => {
      const byLanguage = (picks: Record<string, ResearchPick[]>) =>
        Object.fromEntries(
          Object.entries(picks).map(([language, list]) => [language, list.map((pick) => toPick(pick, task.tools, research))]),
        );
      const ranked = byLanguage(task.picks);
      return {
        id: task.id,
        label: task.label[locale],
        title: task.label[locale],
        usage: t("desk.guide_usage", { count: task.runs }),
        picks: ranked.en,
        picksByLanguage: ranked,
        picksByOutput: Object.fromEntries(Object.entries(task.picksByOutput).map(([output, picks]) => [output, byLanguage(picks)])),
      };
    }),
  }));
}

/** Where Console publishes the edition Redrob Auto routes on. Unauthenticated, like `/pricing`. */
export const REDROB_GUIDE_URL = `${REDROB_BASE_URL}/guide`;

/**
 * The research, as Redrob Auto routes on it: Console's live edition (`GET /v1/guide`), so the ranking
 * a person reads here is the one their requests are routed by. Console keeps only the picks it can
 * route (the `redrob-desk` harness), so a pick ranked on another harness is not listed.
 *
 * The bundled copy below is still the published source Console syncs from, and is what this shows
 * when Console cannot be reached, which is a guide that may be a month behind rather than no guide.
 * Loaded on demand: it is a few megabytes, and only `/guide` reads it.
 */
export async function loadGuideResearch(fetchImpl?: typeof fetch): Promise<GuideResearch> {
  if (fetchImpl) {
    try {
      const response = await fetchImpl(REDROB_GUIDE_URL, { method: "GET", headers: { accept: "application/json" } });
      if (response.ok) {
        const live = GuideResearch.safeParse(await response.json());
        if (live.success) return live.data;
      }
    } catch {
      // Offline, or Console is having a moment: the bundled edition below.
    }
  }
  const module = await import("./model-guide.json");
  return GuideResearch.parse(module.default);
}
