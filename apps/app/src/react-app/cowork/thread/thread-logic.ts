import type { PlanQuestionsProps } from "@redrob-labs/ui";

import { t } from "../../../i18n";
import type { CheckResult, PlanDoc, PlanQuestionData } from "./cowork-blocks";

/**
 * What the thread's actions say and send, kept pure so a test can read them: the answers to
 * Plan's questions as a reply, a plan as the prompt that runs it, the check verdicts, and the
 * buttons on an approval.
 */

/** The answers by question id, as PlanQuestions submits them. */
export type PlanAnswers = NonNullable<PlanQuestionsProps["value"]>;

function chosen(question: PlanQuestionData, value: PlanAnswers): string[] {
  const answer = value[question.id];
  const picked = Array.isArray(answer) ? answer : answer === null || answer === undefined ? [] : [answer];
  return picked.flatMap((index) => {
    const option = question.options[index];
    return option === undefined ? [] : [option];
  });
}

function sentence(text: string): string {
  return /[.!?。…]$/.test(text) ? text : `${text}.`;
}

/** Each question's own typed answer, by question id; it replaces the options picked. */
export type CustomAnswers = Record<string, string>;

/** The answer to one question: the typed text when there is any, else the options picked. */
function answerFor(question: PlanQuestionData, value: PlanAnswers, custom: CustomAnswers): string[] {
  const typed = custom[question.id]?.trim();
  return typed ? [typed] : chosen(question, value);
}

/** The answers as the person's reply: one line per answered question, its question then its choices. */
export function answersToPrompt(questions: PlanQuestionData[], value: PlanAnswers, custom: CustomAnswers = {}): string {
  const lines = questions.flatMap((question) => {
    const picks = answerFor(question, value, custom);
    return picks.length ? [`${question.question} ${sentence(picks.join(", "))}`] : [];
  });
  const body = lines.length ? lines.join("\n") : t("cowork.thread_no_preference");
  // The sentinel lets the transcript hide this synthetic user send while the engine still receives it.
  return `${QUESTION_ANSWER_SENTINEL}${body}`;
}

/** A plan as plain text, the way it goes back to the model. */
export function planToText(plan: PlanDoc): string {
  const lines: string[] = [];
  if (plan.title) lines.push(`# ${plan.title}`);
  if (plan.summary) lines.push(plan.summary);
  for (const section of plan.sections) {
    lines.push(`## ${section.heading}`);
    if (section.body) lines.push(section.body);
    (section.items ?? []).forEach((item, index) => {
      const bullet = section.ordered ? `${index + 1}.` : "-";
      const body = typeof item === "string" ? item : item.lead ? `${item.lead} ${item.text}` : item.text;
      lines.push(`${bullet} ${body}`);
    });
  }
  if (plan.todo.length) {
    lines.push(`## ${t("cowork.thread_plan_todo")}`);
    for (const todo of plan.todo) lines.push(`- ${todo.label}${todo.who ? ` (${todo.who})` : ""}`);
  }
  if (plan.note) lines.push(plan.note);
  return lines.join("\n");
}

/**
 * A zero-width WORD JOINER (U+2060) prefixed to an internal plan-run prompt. It renders as nothing
 * and carries no meaning to the model, but it is a reliable PROVENANCE marker: it tells our own
 * code "this prompt was generated by the Run button", which a visible-text prefix cannot - a human
 * who literally types "Run this plan. ..." would otherwise be misclassified as an internal run and
 * skip complex-prompt planning. Detection keys off this sentinel, not the human-visible words.
 */
const PLAN_RUN_SENTINEL = "\u2060";

/**
 * A provenance sentinel for a synthetic QUESTION-ANSWER send: the choices the person made in the
 * questions card, sent to the engine as a reply. An INVISIBLE SEPARATOR (U+2063), a different
 * character from the plan-run sentinel so neither can be read as the other. Like U+2060 it renders
 * as nothing and is not whitespace, so trim() and BOM stripping keep it (U+FEFF, used before, is a
 * BOM that normalizers drop, which turned an answer into a plan-run).
 */
const QUESTION_ANSWER_SENTINEL = "\u2063";

/** The question-answer sentinel older chats carry (U+2060 U+FEFF), still recognised when read back. */
const LEGACY_QUESTION_ANSWER_SENTINEL = "\u2060\ufeff";

/** Run sends this, in Run mode, so the run agent gets the plan it is to follow. */
export function planRunPrompt(planText: string): string {
  return `${PLAN_RUN_SENTINEL}${t("cowork.thread_run_prompt")}\n\n${planText.trim()}`;
}

/** Whether a prompt is a plan being run, by its provenance sentinel (it routes to the Run agent). */
export function isPlanRunPrompt(prompt: string): boolean {
  // An older chat's answer sentinel also opens with the word joiner, so rule answers out first.
  return prompt.startsWith(PLAN_RUN_SENTINEL) && !isQuestionAnswerPrompt(prompt);
}

/** Whether a prompt is a synthetic question-answer send, by its provenance sentinel. */
export function isQuestionAnswerPrompt(prompt: string): boolean {
  return prompt.startsWith(QUESTION_ANSWER_SENTINEL) || prompt.startsWith(LEGACY_QUESTION_ANSWER_SENTINEL);
}

/**
 * Round 8b: the protocol rule a Plan-mode send carries in its system text, for THIS turn.
 *
 * Seen live (session ses_eaddde07...): a complex prompt went to the plan agent, which ran three web
 * searches and wrote the whole answer as prose - no questions, no plan, so no run, no artifact and no
 * checks. The agent's own prompt says it MAY ask and MAY read the web; this rule makes the turn's
 * shape explicit: a new request gets questions first; the answers get exactly one plan. The research
 * and the deliverable belong to the run that follows.
 */
export function planTurnInstruction(prompt: string): string {
  if (isQuestionAnswerPrompt(prompt)) {
    return [
      "## This turn",
      "The person has answered your questions. Reply with ONE fenced redrob-plan block and nothing else, then stop.",
      "Do not answer the request yet, do not write the deliverable and do not research beyond a quick look you need to plan. The run that follows does the research and writes the deliverable to a file.",
    ].join("\n");
  }
  return [
    "## This turn",
    "This is a new request. Do not answer it yet and do not research it. Reply with ONE fenced redrob-questions block of two to four short questions, each with two to four options and a sensible default, and nothing else, then stop.",
    "Ask what changes the result: the deliverable and its length, the audience, the scope or time frame, and which sources to use. When the answers come back you will write the plan.",
  ].join("\n");
}

/**
 * Whether a prompt is any synthetic Cowork machinery send (a plan being run, or a question-answer
 * reply) that the Cowork transcript should hide while the engine still receives it (item 10).
 */
export function isSyntheticCoworkPrompt(prompt: string): boolean {
  return isPlanRunPrompt(prompt) || isQuestionAnswerPrompt(prompt);
}

/** Where a plan stands: drafted, running, or done. */
export type PlanStage = "draft" | "running" | "done";

/** A plan whose run started and is no longer the latest turn, with the chat idle, is done. */
export function planStatus(input: { local: PlanStage; isLatest: boolean; busy: boolean }): PlanStage {
  if (input.local === "running" && !input.isLatest && !input.busy) return "done";
  return input.local;
}

/** Where one cross-check (Fact check or Council) stands for an answer. */
export type CheckState = "off" | "running" | "done" | "failed";

/** Claims that need a fix, and what the answer missed. */
export function factToFix(result: CheckResult | undefined): number {
  const fact = result?.fact;
  if (!fact) return 0;
  return fact.claims.filter((claim) => claim.verdict !== "holds").length + fact.missed.length;
}

/** The tone + word a finished check shows ON its chip, so the verdict reads without opening it. */
export type CheckVerdict = { tone: "agree" | "mild" | "differ"; label: string };

/**
 * Fact-check confidence as one word, from the claim verdicts + anything missed. "holds" claims are
 * full credit, "partly" half, "wrong" none; each missed point is a full miss. The band:
 *   >=0.9 and nothing missed -> Highly confident (agree)
 *   >=0.7                    -> Mostly correct   (mild)
 *   >=0.4                    -> Some concerns    (differ)
 *   <0.4                     -> Low confidence   (differ)
 * No claims at all reads as Highly confident (nothing to doubt).
 */
export function factConfidence(fact: CheckResult["fact"]): CheckVerdict {
  if (!fact) return { tone: "agree", label: t("cowork.thread_fact_verdict_high") };
  const total = fact.claims.length + fact.missed.length;
  if (total === 0) return { tone: "agree", label: t("cowork.thread_fact_verdict_high") };
  const credit = fact.claims.reduce(
    (sum, claim) => sum + (claim.verdict === "holds" ? 1 : claim.verdict === "partly" ? 0.5 : 0),
    0,
  );
  const ratio = credit / total; // missed points are in the denominator but earn no credit
  if (ratio >= 0.9 && fact.missed.length === 0) return { tone: "agree", label: t("cowork.thread_fact_verdict_high") };
  if (ratio >= 0.7) return { tone: "mild", label: t("cowork.thread_fact_verdict_mostly") };
  if (ratio >= 0.4) return { tone: "differ", label: t("cowork.thread_fact_verdict_some") };
  return { tone: "differ", label: t("cowork.thread_fact_verdict_low") };
}

/**
 * Challenge outcome as one word after the debate, from how many verdict points broke/changed vs
 * held: nothing moved -> Holds up; a few changed -> Mostly holds; several moved -> Weakened; any
 * point broke -> Challenged. No verdict points reads as Holds up.
 */
export function challengeOutcome(challenge: CheckResult["challenge"]): CheckVerdict {
  const verdicts = challenge?.verdict ?? [];
  if (verdicts.length === 0) return { tone: "agree", label: t("cowork.thread_council_verdict_holds") };
  const broke = verdicts.filter((verdict) => verdict.kind === "broke").length;
  const changed = verdicts.filter((verdict) => verdict.kind === "changed").length;
  if (broke > 0) return { tone: "differ", label: t("cowork.thread_council_verdict_challenged") };
  if (changed === 0) return { tone: "agree", label: t("cowork.thread_council_verdict_holds") };
  const movedRatio = changed / verdicts.length;
  if (movedRatio <= 0.34) return { tone: "mild", label: t("cowork.thread_council_verdict_mostly") };
  return { tone: "differ", label: t("cowork.thread_council_verdict_weakened") };
}

export type PermissionReply = "once" | "always" | "reject";

export type ApprovalActions = {
  onApprove: () => void;
  onReject: () => void;
  onAlways?: () => void;
};

/**
 * An approval's buttons: Approve answers once and Reject rejects. Always widens permission
 * for the rest of the session, so only Developer mode offers it.
 */
export function approvalActions(
  requestId: string,
  respond: (requestId: string, reply: PermissionReply) => void,
  developerMode: boolean,
): ApprovalActions {
  const actions: ApprovalActions = {
    onApprove: () => respond(requestId, "once"),
    onReject: () => respond(requestId, "reject"),
  };
  if (developerMode) actions.onAlways = () => respond(requestId, "always");
  return actions;
}

type ToolPartLike = { type: string; toolName?: unknown; state?: unknown; input?: unknown };

function record(value: unknown): Record<string, unknown> | null {
  if (typeof value === "object" && value !== null && !Array.isArray(value)) return Object.fromEntries(Object.entries(value));
  if (typeof value !== "string") return null;
  try {
    return record(JSON.parse(value));
  } catch {
    return null;
  }
}

const MEMORY_SAVE = /(^|[._:/-])postmemory$/i;

/**
 * What a finished tool call saved to memory, or null. The agent saves a note by executing the
 * `postMemory` capability with a body of `{ content }`; nothing else in a transcript says a
 * note was kept.
 */
export function memorySavedFrom(part: ToolPartLike): string | null {
  if (part.state !== "output-available" || typeof part.toolName !== "string") return null;
  if (!/(execute_capability|redrob_execute)$/.test(part.toolName)) return null;
  const input = record(part.input);
  const name = input?.name ?? input?.id;
  if (typeof name !== "string" || !MEMORY_SAVE.test(name.trim())) return null;
  const content = record(input?.body)?.content;
  return typeof content === "string" && content.trim() ? content.trim() : null;
}
